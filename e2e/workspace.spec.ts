import { expect, test } from '@playwright/test'

test('create a bottle, upload and launch a program, inspect logs, and navigate', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '我的 Bottles' })).toBeVisible()
  await page.getByRole('button', { name: '新建 Bottle', exact: true }).first().click()
  await page.getByLabel('Bottle 名称').fill('我的游戏空间')
  await page.getByRole('button', { name: '创建 Bottle', exact: true }).click()
  await expect(page.getByRole('link', { name: '我的游戏空间', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '我的游戏空间', exact: true }).click()
  await expect(page.getByText('已就绪', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: '添加程序', exact: true }).first().click()
  await page.getByLabel('程序文件').setInputFiles({ name: 'demo.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('fixture executable') })
  await page.getByLabel('程序名称').fill('演示程序')
  await page.getByRole('button', { name: '上传并添加', exact: true }).click()
  await expect(page.getByText('演示程序', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '运行 演示程序' }).click()
  await page.getByRole('link', { name: '任务中心' }).click()
  await expect(page.getByText('启动程序', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: '查看日志' }).first().click()
  await expect(page.getByText('operation complete', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('link', { name: '程序库' }).click()
  await expect(page.getByText('演示程序', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '运行环境', exact: true }).click()
  await expect(page.getByRole('heading', { name: '运行环境', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

